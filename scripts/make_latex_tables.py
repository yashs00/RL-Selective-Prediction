"""Emit the paper's LaTeX tables from `results/results.parquet`.

Exists to honour project_plan.md §8's non-negotiable rule: *no number in
the paper should exist anywhere except as a query against the results
file* -- never hand-typed. `main.tex` `\\input{}`s the files written here,
so re-running the sweep and re-running this script updates the paper
without anyone editing a number by hand (and without the classic failure
where a table and its surrounding prose drift apart).

Writes to `paper/tables/*.tex`:
  tab_main_aurc.tex        -- headline AURC per dataset x method
  tab_agg_vs_best_single.tex -- the comparison that actually tests
                                *aggregation* rather than "beats MSP"
  tab_tier_a_degeneracy.tex  -- |Spearman| of each Tier-A signal vs MSP
  tab_conformal.tex          -- RQ3 coverage at guaranteed risk
  tab_subgroup.tex           -- RQ4 subgroup max-min gap

Usage:
    python scripts/make_latex_tables.py --tiers AC
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from make_tables import select_tiers  # noqa: E402

RESULTS_PATH = ROOT / "results" / "results.parquet"
TABLE_DIR = ROOT / "paper" / "tables"
TABLE_DIR.mkdir(exist_ok=True, parents=True)

# Dataset display names and their class counts, so the tables can be read
# without cross-referencing the setup section.
DATASET_META = {
    "adult": ("Adult", 2),
    "german_credit": ("German Credit", 2),
    "electricity": ("Electricity$^{\\dagger}$", 2),
    "bank_marketing": ("Bank Marketing", 2),
    "eeg_eye_state": ("EEG Eye State", 2),
    "kr_vs_kp": ("Kr-vs-Kp", 2),
    "magic_telescope": ("Magic Telescope", 2),
    "nomao": ("Nomao", 2),
    "phoneme": ("Phoneme", 2),
    "satimage": ("Satimage", 6),
    "wine_quality_white": ("Wine Quality", 7),
    "letter": ("Letter", 26),
}
TIER_C = [
    "signal_knn_distance", "signal_mahalanobis",
    "signal_trust_score", "signal_local_label_agreement",
]


def _esc(s: str) -> str:
    return s.replace("_", "\\_")


def _order(datasets) -> list[str]:
    """Binary datasets first, then multiclass by class count -- the axis the
    degeneracy argument turns on."""
    return sorted(datasets, key=lambda d: (DATASET_META.get(d, (d, 99))[1], d))


def _name(ds: str) -> str:
    return DATASET_META.get(ds, (_esc(ds), 0))[0]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tiers", default="AC")
    args = ap.parse_args()

    df = select_tiers(pd.read_parquet(RESULTS_PATH), args.tiers)
    aurc = df[df.subgroup == "AURC"]

    # ---------------- main AURC table --------------------------------
    per = {}
    for ds, g in aurc.groupby("dataset"):
        per[ds] = g.pivot(index="seed", columns="method", values="value")

    headline = ["signal_msp", "A0_rank", "A1_logreg", "A2_mlp_bce",
                "A2_mlp_loss3", "A2_adaptive_loss3", "oracle", "random"]
    lines = [
        "% GENERATED by scripts/make_latex_tables.py -- do not edit by hand.",
        "\\begin{table*}[t]", "\\centering",
        "\\caption{AURC (lower is better), mean over 10 seeds, signal tiers "
        f"{args.tiers}. $\\dagger$ = temporal-shift split.}}",
        "\\label{tab:main_aurc}",
        "\\begin{tabular}{l r " + "r" * len(headline) + "}", "\\toprule",
        "Dataset & $K$ & " + " & ".join(_esc(m) for m in headline) + " \\\\", "\\midrule",
    ]
    for ds in _order(per):
        p = per[ds].mean()
        cells = []
        for m in headline:
            cells.append(f"{p[m]:.4f}" if m in p else "--")
        lines.append(f"{_name(ds)} & {DATASET_META.get(ds,('',0))[1]} & " + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""]
    (TABLE_DIR / "tab_main_aurc.tex").write_text("\n".join(lines))

    # -------- aggregation vs BEST SINGLE SIGNAL (the real test) -------
    lines = [
        "% GENERATED by scripts/make_latex_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{Does aggregation add anything \\emph{beyond the best "
        "single signal}? Negative $\\Delta$ favours the aggregator. "
        "Comparing to MSP alone (column 4) overstates the case on Wine, "
        "where a single Tier-C signal, not aggregation, does the work.}",
        "\\label{tab:agg_vs_single}",
        "\\begin{tabular}{l r r l r r}", "\\toprule",
        "Dataset & $K$ & MSP & Best single & Best agg. & $\\Delta$ vs.\\ best single \\\\",
        "\\midrule",
    ]
    for ds in _order(per):
        p = per[ds].mean()
        sing = {k: v for k, v in p.items() if k.startswith("signal_")}
        aggs = {k: v for k, v in p.items() if k.startswith(("A0", "A1", "A2"))}
        bs, ba = min(sing, key=sing.get), min(aggs, key=aggs.get)
        rel = 100.0 * (aggs[ba] - sing[bs]) / sing[bs]
        lines.append(
            f"{_name(ds)} & {DATASET_META.get(ds,('',0))[1]} & {p['signal_msp']:.4f} & "
            f"{_esc(bs.replace('signal_',''))}\\,({sing[bs]:.4f}) & {aggs[ba]:.4f} & "
            f"{rel:+.1f}\\% \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABLE_DIR / "tab_agg_vs_best_single.tex").write_text("\n".join(lines))

    # ---------------- RQ3 conformal ----------------------------------
    conf = df[df.subgroup.str.startswith("conformal_alpha")]
    piv = conf.pivot_table(index="dataset", columns="subgroup", values="coverage", aggfunc="mean")
    alphas = ["conformal_alpha_0.01", "conformal_alpha_0.02",
              "conformal_alpha_0.05", "conformal_alpha_0.1"]
    base_err = (
        aurc[aurc.method == "signal_msp"].groupby("dataset")["value"].mean()
    )
    lines = [
        "% GENERATED by scripts/make_latex_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{RQ3: coverage attained at a guaranteed selective risk "
        "$\\le\\alpha$ ($\\delta=0.1$), using the Hoeffding--Bentkus bound. "
        "Zeros are correct behaviour, not failure: a risk target below the "
        "model's own error rate is unattainable at any positive coverage.}",
        "\\label{tab:conformal}",
        "\\begin{tabular}{l r r r r}", "\\toprule",
        "Dataset & $\\alpha{=}0.01$ & $0.02$ & $0.05$ & $0.10$ \\\\", "\\midrule",
    ]
    for ds in _order(piv.index):
        row = piv.loc[ds]
        lines.append(
            f"{_name(ds)} & " + " & ".join(
                f"{row[a]:.3f}" if a in row and pd.notna(row[a]) else "--" for a in alphas
            ) + " \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABLE_DIR / "tab_conformal.tex").write_text("\n".join(lines))

    # ---------------- RQ4 subgroup -----------------------------------
    gaps = df[df.subgroup == "max_min_gap@0.8"]
    lines = [
        "% GENERATED by scripts/make_latex_tables.py -- do not edit by hand.",
        "\\begin{table}[t]", "\\centering",
        "\\caption{RQ4: max--min subgroup selective-risk gap at 80\\% "
        "overall coverage (mean over 10 seeds). Higher is worse. "
        "Aggregation does not reduce the disparity and on Adult widens it.}",
        "\\label{tab:subgroup}",
        "\\begin{tabular}{l r r r}", "\\toprule",
        "Dataset & MSP & Best agg. & $\\Delta$ \\\\", "\\midrule",
    ]
    for ds, g in gaps.groupby("dataset"):
        p = g.pivot(index="seed", columns="method", values="value").mean()
        if "signal_msp" not in p:
            continue
        aggs = {k: v for k, v in p.items() if k.startswith(("A0", "A1", "A2"))}
        if not aggs:
            continue
        ba = min(aggs, key=aggs.get)
        lines.append(
            f"{_name(ds)} & {p['signal_msp']:.4f} & {aggs[ba]:.4f} & "
            f"{aggs[ba]-p['signal_msp']:+.4f} \\\\"
        )
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    (TABLE_DIR / "tab_subgroup.tex").write_text("\n".join(lines))

    for f in ["tab_main_aurc", "tab_agg_vs_best_single", "tab_conformal", "tab_subgroup"]:
        print(f"wrote {TABLE_DIR / (f + '.tex')}")


if __name__ == "__main__":
    main()
